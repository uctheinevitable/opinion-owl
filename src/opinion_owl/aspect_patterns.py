# Compile once at import time. Regexes are case-insensitive because Reddit text
# mixes "RAM", "ram" and "Ram" freely.
COMPILED = {
    aspect: [re.compile(p, re.IGNORECASE) for p in patterns]
    for aspect, patterns in ASPECT_PATTERNS.items()
}


